//! 下载成品的封面 / 歌词内嵌（「下载存储方式 = 音乐内嵌」，用户 2026-10
//! 「下载歌曲时同时将封面和歌词内嵌到歌曲中」）。读 + 写都走 lofty：
//! MP3（ID3v2 APIC/USLT）/ FLAC（VORBIS_COMMENT + METADATA_BLOCK_PICTURE）/
//! M4A（ilst covr / ©lyr）/ WAV（ID3v2 chunk）/ OGG / Opus 等；白名单外的
//! 格式一律 [`EmbedOutcome::Skipped`]，由调用方（download.rs）降级为同目录
//! sidecar 文件，内容不丢。
//!
//! 安全口径（设计文档 §PC-2「绝不毁歌」）：**绝不在原文件上原地改**。先复制
//! `<原名>.embedtmp` 副本，在副本上读改写，成功后 rename 回去；任何一步
//! 失败都删副本、原文件字节不变。
//!
//! 写入策略（音源文件自带的内容更权威，只补缺、不覆盖）：
//! - 标题 / 歌手 / 专辑：原标签缺失（或空串）才写入；
//! - 封面：原文件已有封面（任意一张）就不动；只嵌 jpg / png（标签封面的
//!   事实标准，webp / gif 由 sidecar 兜底）；
//! - 歌词：恒写入（每次都是刚取到的最新词，[`update_embedded_lyric`] 亦然）。

use lofty::config::WriteOptions;
use lofty::file::TaggedFileExt;
use lofty::picture::{MimeType, Picture, PictureType};
use lofty::prelude::*;
use lofty::probe::Probe;
use lofty::tag::{ItemKey, ItemValue, Tag, TagItem, TagExt, TagType};
use std::path::{Path, PathBuf};

/// 支持内嵌的扩展名（小写比较，设计文档 §PC-1 白名单）。不认的格式一律
/// [`EmbedOutcome::Skipped`]，由调用方降级为同目录 sidecar。
/// 注意 `.part` / `.embedtmp` 都不在表内。
pub const SUPPORTED_EXTS: &[&str] = &[
    "mp3", "flac", "m4a", "mp4", "aac", "wav", "ogg", "opus", "wma",
];

/// 单次内嵌的结果，三类各自去向（见 download.rs 的降级逻辑）：
/// - Done：成功（含「按策略无需改动」）
/// - Skipped：这个文件不适合内嵌（扩展名不在白名单 / lofty 探测不出已知
///   音频类型）→ 调用方降级 sidecar
/// - Failed：中途出错（IO / 标签写回失败）→ 调用方降级 sidecar
#[derive(Debug)]
pub enum EmbedOutcome {
    Done,
    Skipped(String),
    Failed(String),
}

/// 内嵌用封面。只收 jpg / png 字节——[`embeddable_png`] 把关。
#[derive(Debug)]
pub struct EmbedCover {
    pub data: Vec<u8>,
    /// true = PNG，false = JPEG
    pub png: bool,
}

/// 一次内嵌要写的内容（owned：调用方在 blocking 池里跨线程转交）。
/// None 的项不动。写入策略见模块注释。
#[derive(Debug)]
pub struct EmbedPayload {
    pub title: String,
    pub singer: String,
    pub album: String,
    pub cover: Option<EmbedCover>,
    pub lyric: Option<String>,
}

/// 封面字节能否进标签。`Some(true)` = PNG，`Some(false)` = JPEG，
/// `None` = 不能内嵌（webp / gif / 未识别）→ 调用方按 sidecar 落盘。
pub fn embeddable_png(bytes: &[u8]) -> Option<bool> {
    if bytes.starts_with(&[0xFF, 0xD8, 0xFF]) {
        Some(false)
    } else if bytes.starts_with(&[0x89, 0x50, 0x4E, 0x47]) {
        Some(true)
    } else {
        None
    }
}

/// 歌词落在哪个 ItemKey：ID3v2 只有 USLT（无时间戳纯文本帧），lofty 把它
/// 映射到 [`ItemKey::UnsyncLyrics`]（[`ItemKey::Lyrics`] 在 ID3v2 无映射，
/// `Tag::insert` 会静默丢弃——见 lofty tag/item.rs 的 USLT 映射表）；其余
/// 格式（VorbisComments 的 Lyrics 字段 / MP4 的 ©lyr / APE）用
/// [`ItemKey::Lyrics`]。LRC 正文（带 [00:01.00] 时间戳）按行业惯例原样
/// 塞进这些「无同步」容器，播放器按纯文本展示或自行解析。
fn lyric_key_for(tag_type: TagType) -> ItemKey {
    match tag_type {
        TagType::Id3v2 => ItemKey::UnsyncLyrics,
        _ => ItemKey::Lyrics,
    }
}

/// 把标题 / 歌手 / 专辑 / 封面 / 歌词内嵌进 `path`（策略见模块注释）。
pub fn embed_tags(path: &Path, payload: &EmbedPayload) -> EmbedOutcome {
    embed_via_tmp(path, |tag| {
        let mut changed = false;
        if !payload.title.trim().is_empty() && tag.title().is_none_or(|v| v.trim().is_empty()) {
            tag.set_title(payload.title.clone());
            changed = true;
        }
        if !payload.singer.trim().is_empty() && tag.artist().is_none_or(|v| v.trim().is_empty()) {
            tag.set_artist(payload.singer.clone());
            changed = true;
        }
        if !payload.album.trim().is_empty() && tag.album().is_none_or(|v| v.trim().is_empty()) {
            tag.set_album(payload.album.clone());
            changed = true;
        }
        if let Some(cover) = &payload.cover {
            // 原文件已有封面就不动（音源自带的更权威），只补缺
            if tag.pictures().is_empty() {
                let mime = if cover.png { MimeType::Png } else { MimeType::Jpeg };
                let picture = Picture::unchecked(cover.data.clone())
                    .pic_type(PictureType::CoverFront)
                    .mime_type(mime)
                    .build();
                tag.push_picture(picture);
                changed = true;
            }
        }
        if let Some(lrc) = &payload.lyric {
            if !lrc.trim().is_empty() {
                let key = lyric_key_for(tag.tag_type());
                tag.insert(TagItem::new(key, ItemValue::Text(lrc.clone())));
                changed = true;
            }
        }
        Ok(changed)
    })
}

/// 只更新歌词字段（`write_download_lyric` 命令的内嵌路径）。恒写入：
/// 下载完成当时没词、之后前端才取到的场景，词是越新越好。
pub fn update_embedded_lyric(path: &Path, lrc: &str) -> EmbedOutcome {
    embed_via_tmp(path, |tag| {
        if lrc.trim().is_empty() {
            return Ok(false); // 纯音乐 / 空词：不落、也不动文件
        }
        let key = lyric_key_for(tag.tag_type());
        tag.insert(TagItem::new(key, ItemValue::Text(lrc.to_string())));
        Ok(true)
    })
}

/// [`embed_via_tmp`] 内部错误的两档：Skip = 这个文件不适合内嵌；
/// Fail = 写入过程出错。
enum MutateErr {
    Skip(String),
    Fail(String),
}

/// 公共骨架：白名单检查 → 复制 `<原名>.embedtmp` → 副本上读改写 → rename
/// 回去。mutate 返回「是否有实际改动」：无改动就不重写文件（省一次全文件
/// IO）。任何一步失败都删副本，原文件字节不变。
fn embed_via_tmp(
    path: &Path,
    mutate: impl FnOnce(&mut Tag) -> Result<bool, MutateErr>,
) -> EmbedOutcome {
    if !ext_supported(path) {
        return EmbedOutcome::Skipped("格式不在内嵌白名单".to_string());
    }
    let tmp = tmp_sibling(path);
    if let Err(e) = std::fs::copy(path, &tmp) {
        return EmbedOutcome::Failed(format!("复制临时副本失败: {e}"));
    }
    let result = (|| -> Result<bool, MutateErr> {
        // lofty 的 Probe 先按扩展名猜类型（`.embedtmp` 猜不出），必须再按
        // 内容重新探测；探测不出已知音频类型 → Skip：调用方降级 sidecar，
        // 封面 / 歌词照样不丢
        let tagged = Probe::open(&tmp)
            .and_then(|probe| probe.guess_file_type().map_err(Into::into))
            .and_then(|probe| probe.read())
            .map_err(|e| MutateErr::Skip(format!("无法识别的音频内容: {e}")))?;
        // 取「主标签」（mp3 = ID3v2，flac = VorbisComments，m4a = ilst…）；
        // 原本没标签的，按目标格式的主标签类型新建一个空标签，save_to_path
        // 会落到对应容器
        let mut tag = match tagged.primary_tag() {
            Some(t) => t.clone(),
            None => Tag::new(tagged.primary_tag_type()),
        };
        let changed = mutate(&mut tag)?;
        if !changed {
            return Ok(false);
        }
        tag.save_to_path(&tmp, WriteOptions::default())
            .map_err(|e| MutateErr::Fail(format!("标签写回失败: {e}")))?;
        Ok(true)
    })();
    match result {
        Ok(true) => match std::fs::rename(&tmp, path) {
            Ok(()) => EmbedOutcome::Done,
            Err(e) => {
                let _ = std::fs::remove_file(&tmp);
                EmbedOutcome::Failed(format!("替换原文件失败: {e}"))
            }
        },
        Ok(false) => {
            let _ = std::fs::remove_file(&tmp);
            EmbedOutcome::Done
        }
        Err(MutateErr::Skip(why)) => {
            let _ = std::fs::remove_file(&tmp);
            EmbedOutcome::Skipped(why)
        }
        Err(MutateErr::Fail(why)) => {
            let _ = std::fs::remove_file(&tmp);
            EmbedOutcome::Failed(why)
        }
    }
}

fn ext_supported(path: &Path) -> bool {
    path.extension()
        .and_then(|e| e.to_str())
        .map(|e| SUPPORTED_EXTS.contains(&e.to_ascii_lowercase().as_str()))
        .unwrap_or(false)
}

/// `<原名>.embedtmp`：与原文件同目录（rename 不能跨卷），扩展名不在白名单，
/// 绝不会被当成音频误处理。
fn tmp_sibling(path: &Path) -> PathBuf {
    let mut name = path.as_os_str().to_os_string();
    name.push(".embedtmp");
    PathBuf::from(name)
}

