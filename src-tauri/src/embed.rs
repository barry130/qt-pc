    /// 把 fixture 写到给定路径（无 ffmpeg 环境的主链路测试用）。
    fn minimal_mp3(path: &Path) {
        std::fs::write(path, MINIMAL_MP3).unwrap();
    }

    fn tmp_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("qt-embed-test-{}-{name}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    /// 本机有 ffmpeg 时用真编码文件（覆盖 flac / m4a / wav 的真实容器结构）；
    /// 没有就返回 None，由调用方跳过对应用例。
    fn ffmpeg_make(dir: &Path, name: &str, codec: &[&str]) -> Option<PathBuf> {
        let out = dir.join(name);
        let ok = std::process::Command::new("ffmpeg")
            .args([
                "-y",
                "-hide_banner",
                "-loglevel",
                "error",
                "-f",
                "lavfi",
                "-i",
                "sine=frequency=440:duration=0.3",
            ])
            .args(codec)
            .arg(&out)
            .status()
            .ok()?
            .success();
        ok.then(|| out)
    }

    /// 封面字节只需魔数正确：lofty 只存取字节、不解码图片。
    fn png_bytes() -> Vec<u8> {
        let mut v = vec![0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];
        v.extend_from_slice(b"qt-fake-png-body");
        v
    }

    fn jpg_bytes() -> Vec<u8> {
        let mut v = vec![0xFF, 0xD8, 0xFF, 0xE0];
        v.extend_from_slice(b"qt-fake-jpg-body");
        v
    }

    fn sample_payload(png: bool) -> EmbedPayload {
        EmbedPayload {
            title: "测试标题".into(),
            singer: "测试歌手".into(),
            album: "测试专辑".into(),
            cover: Some(EmbedCover {
                data: if png { png_bytes() } else { jpg_bytes() },
                png,
            }),
            lyric: Some("[00:01.00]第一行\n[00:02.00]第二行".into()),
        }
    }

    fn probe_tag(path: &Path) -> Tag {
        let f = Probe::open(path).unwrap().read().unwrap();
        f.primary_tag().or_else(|| f.first_tag()).cloned().unwrap()
    }

    /// 内嵌成功后的统一回读校验（标题 / 歌手 / 专辑 / 封面 / 歌词 + 临时副本清理）。
    fn assert_embedded(path: &Path, payload: &EmbedPayload) {
        let tag = probe_tag(path);
        assert_eq!(tag.title().as_deref(), Some("测试标题"));
        assert_eq!(tag.artist().as_deref(), Some("测试歌手"));
        assert_eq!(tag.album().as_deref(), Some("测试专辑"));
        assert_eq!(tag.pictures().len(), 1);
        assert_eq!(
            tag.pictures()[0].data(),
            payload.cover.as_ref().unwrap().data.as_slice()
        );
        assert_eq!(
            tag.pictures()[0].mime_type(),
            Some(if payload.cover.as_ref().unwrap().png {
                &MimeType::Png
            } else {
                &MimeType::Jpeg
            })
        );
        let lyric_read = tag
            .get_string(ItemKey::Lyrics)
            .or_else(|| tag.get_string(ItemKey::UnsyncLyrics));
        assert_eq!(lyric_read, payload.lyric.as_deref());
        // 成功替换后临时副本必须已清掉
        assert!(!tmp_sibling(path).exists());
    }

    #[test]
    fn mp3_embed_roundtrip() {
        let dir = tmp_dir("mp3-rt");
        let path = ffmpeg_make(&dir, "t.mp3", &[]).unwrap_or_else(|| {
            let p = dir.join("t.mp3");
            minimal_mp3(&p);
            p
        });
        let payload = sample_payload(true);
        match embed_tags(&path, &payload) {
            EmbedOutcome::Done => {}
            other => panic!("内嵌应成功: {other:?}"),
        }
        assert_embedded(&path, &payload);
    }

    /// flac / m4a / wav 是下载最常见的无损与压缩目标格式，用 ffmpeg 真文件
    /// 各嵌一遍，覆盖三种不同的标签容器（VORBIS_COMMENT / ilst / RIFF ID3）。
    #[test]
    fn flac_m4a_wav_roundtrip() {
        for (name, codec) in [
            ("t.flac", &[][..] as &[&str]),
            ("t.m4a", &["-c:a", "aac", "-b:a", "32k"][..]),
            ("t.wav", &["-c:a", "pcm_s16le"][..]),
        ] {
            let dir = tmp_dir(name.trim_start_matches('t').trim_start_matches('.'));
            let Some(path) = ffmpeg_make(&dir, name, codec) else {
                eprintln!("跳过 {name}：本机无 ffmpeg");
                continue;
            };
            let payload = sample_payload(false); // jpg 封面也测到
            match embed_tags(&path, &payload) {
                EmbedOutcome::Done => {}
                other => panic!("{name} 内嵌应成功: {other:?}"),
            }
            assert_embedded(&path, &payload);
        }
    }

    /// 写入策略：标题 / 封面已有值不覆盖，歌词恒写最新。
    #[test]
    fn preserves_existing_values() {
        let dir = tmp_dir("preserve");
        let path = dir.join("t.mp3");
        minimal_mp3(&path);
        embed_tags(&path, &sample_payload(true));
        // 第二轮换了标题和封面：原值优先；歌词换成新的
        let mut second = sample_payload(false);
        second.title = "第二版标题".into();
        second.lyric = Some("[00:09.99]新词".into());
        match embed_tags(&path, &second) {
            EmbedOutcome::Done => {}
            other => panic!("第二轮应成功: {other:?}"),
        }
        let tag = probe_tag(&path);
        assert_eq!(tag.title().as_deref(), Some("测试标题")); // 没被覆盖
        assert_eq!(tag.pictures().len(), 1);
        assert_eq!(tag.pictures()[0].data(), png_bytes().as_slice()); // 还是第一轮的封面
        assert_eq!(tag.get_string(ItemKey::UnsyncLyrics), Some("[00:09.99]新词")); // 歌词换新
    }

    #[test]
    fn update_lyric_only_and_empty_is_noop() {
        let dir = tmp_dir("upd-lyric");
        let path = dir.join("t.mp3");
        minimal_mp3(&path);
        match update_embedded_lyric(&path, "[00:05.00]补写的词") {
            EmbedOutcome::Done => {}
            other => panic!("补写歌词应成功: {other:?}"),
        }
        let tag = probe_tag(&path);
        assert_eq!(tag.get_string(ItemKey::UnsyncLyrics), Some("[00:05.00]补写的词"));
        assert_eq!(tag.title(), None); // 只动歌词
        // 空词 = 无操作：不改文件，也返回 Done
        match update_embedded_lyric(&path, "   ") {
            EmbedOutcome::Done => {}
            other => panic!("空词应为无操作: {other:?}"),
        }
        let tag = probe_tag(&path);
        assert_eq!(tag.get_string(ItemKey::UnsyncLyrics), Some("[00:05.00]补写的词"));
    }

    /// 边界：白名单外直接 Skipped；白名单内文件缺失 Failed；
    /// 白名单内但内容不是音频 Skipped 且不留临时副本。
    #[test]
    fn unsupported_and_garbage_files() {
        let dir = tmp_dir("skip");
        // 白名单外的扩展名：直接 Skipped（不碰文件）
        let txt = dir.join("t.txt");
        std::fs::write(&txt, b"hello").unwrap();
        assert!(matches!(
            embed_tags(&txt, &sample_payload(true)),
            EmbedOutcome::Skipped(_)
        ));
        assert!(matches!(
            update_embedded_lyric(&txt, "词"),
            EmbedOutcome::Skipped(_)
        ));
        // 白名单内但文件不存在：复制阶段就失败 → Failed
        let missing = dir.join("missing.mp3");
        assert!(matches!(
            embed_tags(&missing, &sample_payload(true)),
            EmbedOutcome::Failed(_)
        ));
        // 白名单内但内容不是音频：探测失败 → Skipped，且不留临时副本
        let garbage = dir.join("garbage.flac");
        std::fs::write(&garbage, b"definitely not a flac stream").unwrap();
        match embed_tags(&garbage, &sample_payload(true)) {
            EmbedOutcome::Skipped(_) => {}
            other => panic!("垃圾内容应 Skipped: {other:?}"),
        }
        assert!(!tmp_sibling(&garbage).exists());
    }
